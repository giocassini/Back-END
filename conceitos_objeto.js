
// Object (Objetos)
// Um ovjeto agrupa várias informações dentro de uma mesma variável, usando chave e valor

let pessoa = {
    nome: "Ana",
    idade: 18,
    cidade: "São Paulo" // O último elemento não precisa de vírgula
};

console.log(`Nome: ${pessoa.nome}`);
console.log(`A ${pessoa.nome} tem ${pessoa.idade} anos de idade`);
console.log(`-----------------------------------------------`)

// Crie um objeto chamado `carro` com as propriedades `marca`, `modelo` e `ano`.
